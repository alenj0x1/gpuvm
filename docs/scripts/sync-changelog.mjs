// Copies the repo's CHANGELOG.md (English) and CHANGELOG.es.md (Spanish) into the docs content collection,
// so the Changelog page always shows the current changes. Runs on `predev` and `prebuild`.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const docsRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// CHANGELOG_DIR lets you point to other files while testing; by default, the repository root.
const sourceDir = resolve(process.env.CHANGELOG_DIR ?? join(docsRoot, '..'));
const contentDir = join(docsRoot, 'src', 'content', 'docs');

const targets = [
  {
    source: 'CHANGELOG.md',
    target: join(contentDir, 'changelog.md'),
    title: 'Changelog',
    description: 'Notable changes in each GpuVM version.',
    missing: 'The changelog is not available yet.',
  },
  {
    source: 'CHANGELOG.es.md',
    target: join(contentDir, 'es', 'changelog.md'),
    title: 'Registro de cambios',
    description: 'Cambios importantes en cada versión de GpuVM.',
    missing: 'El registro de cambios todavía no está disponible.',
  },
];

const yaml = (text) => JSON.stringify(text);

function toPage(markdown) {
  return markdown
    .replace(/^﻿/, '')
    .replace(/\r\n/g, '\n')
    // Starlight renders the frontmatter title as the page heading.
    .replace(/^#\s+.*\n+/, '')
    // Language switch lines that link to the other CHANGELOG file only make sense on GitHub.
    .replace(/^.*\]\(CHANGELOG(\.es)?\.md\).*\n+/gm, '')
    // Only released versions: the section of changes waiting for the next one, its compare link and the
    // line that explains it stay on GitHub.
    .replace(/^## \[(Unreleased|Sin publicar)\]\n[\s\S]*?(?=^## |(?![\s\S]))/m, '')
    .replace(/^\[(Unreleased|Sin publicar)\]: .*\n?/gm, '')
    .replace(/^.*scripts\/release\.py.*\n+/gm, '')
    .trim();
}

for (const t of targets) {
  const sourcePath = join(sourceDir, t.source);
  let body;
  if (existsSync(sourcePath)) {
    body = toPage(readFileSync(sourcePath, 'utf8'));
    console.log(`sync-changelog: ${t.source} -> ${t.target.slice(docsRoot.length + 1)}`);
  } else {
    body = t.missing;
    console.warn(`sync-changelog: ${sourcePath} not found; writing a placeholder page.`);
  }
  const frontmatter = [
    '---',
    `title: ${yaml(t.title)}`,
    `description: ${yaml(t.description)}`,
    // "Edit page" goes to the source file at the repo root, not to this generated copy.
    `editUrl: ${yaml(`https://github.com/alenj0x1/gpuvm/edit/main/${t.source}`)}`,
    '---',
  ].join('\n');
  const notice = `<!-- Generated by scripts/sync-changelog.mjs from ${t.source}. Edit that file at the repo root, not this one. -->`;
  const page = `${frontmatter}\n\n${notice}\n\n${body}\n`;
  mkdirSync(dirname(t.target), { recursive: true });
  writeFileSync(t.target, page);
}
